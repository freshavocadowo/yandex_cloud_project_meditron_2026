import pytest

from app.anonymize import anonymize, residual_identifiers


@pytest.mark.parametrize("line,expected", [
    ("Пациентка: Анна Петровна Сидорова, д.р. 21.02.1948, возраст 73 года.",
     "Пациентка: [ФИО], д.р. [ДР], возраст [ВОЗРАСТ]."),
    ("Ф.И.О.: Иван Иванович Петров. д.р. 06.01.1950; возраст 71 лет.",
     "Ф.И.О.: [ФИО]. д.р. [ДР]; возраст [ВОЗРАСТ]."),
    ("Пациент: Отто Эдуардович Бисмарков (д.р. 01.04.1945, 75 лет).",
     "Пациент: [ФИО] (д.р. [ДР], [ВОЗРАСТ])."),
    ("Пациент: Олег Олегович Шах-Джаханов; д.р. 01.04.1955; 65 лет. Период лечения: с 07.11.2020 по 16.11.2020.",
     "Пациент: [ФИО]; д.р. [ДР]; [ВОЗРАСТ]. Период лечения: с 07.11.2020 по 16.11.2020."),
    ("Пациент: Васко даГамович Индийский, д.р. 20.05.1958, возраст 66 лет.",
     "Пациент: [ФИО], д.р. [ДР], возраст [ВОЗРАСТ]."),
    ("Пациент: Тимур Темирович Степняков; условная дата 1956 г. (по документам); около 64 лет. Поступил 05.03.2020.",
     "Пациент: [ФИО]; условная дата [ДР] г. (по документам); около [ВОЗРАСТ]. Поступил 05.03.2020."),
])
def test_patient_line_variants(line, expected):
    result = anonymize(line)
    assert result.text == expected
    assert result.residual == []


