def test_clinical_content_untouched():
    text = ("Поступила 13.01.2022. Выписана 17.01.2022.\nЛечащий врач: ____________\n"
            "ЭКГ от 13.01.2022: синусовый ритм, ЧСС 108 уд/мин. АД 118/76 мм рт. ст.\n"
            "Первые сутки — мониторинг. Тропонин положительный. Клопидогрел 75 мг 1 раз в день.")
    result = anonymize(text)
    assert result.text == text and result.spans == []


def test_repeated_surname_in_other_case_masked():
    text = "Пациентка: Жанна Дарковна Орлеанская, д.р. 06.01.1950.\nОрлеанской выполнена КАГ."
    result = anonymize(text)
    assert "Орлеанск" not in result.text
    assert result.text.endswith("[ФИО] выполнена КАГ.")
    assert [result.text[s.start:s.end] for s in result.spans] == ["[ФИО]", "[ДР]", "[ФИО]"]


def test_residual_detects_unrecognized_name():
    assert residual_identifiers("Пациент: ван дер Иванов, д.р. 01.01.1950") == ["dob", "fio"]
    assert residual_identifiers("Пациент: [ФИО], д.р. [ДР]") == []


def test_corpus_fully_masked(corpus):
    from app.ingest import load_path
    for path in corpus:
        result = anonymize(load_path(path).text)
        assert result.residual == [], path.name
        assert {s.kind for s in result.spans} >= {"fio", "dob", "age", "id"}, path.name
